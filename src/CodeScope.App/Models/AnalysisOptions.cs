using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Text.Json.Serialization;

namespace CodeScope.Models;

/// <summary>
/// Every analysis-relevant option the pinned scc backend exposes, expressed in
/// the GUI's own vocabulary. Values mirror the backend's documented defaults so
/// a pristine install reproduces the engine's stock behaviour.
///
/// Defaults are the ones printed by `scc --help`:
///   --avg-wage 56286   --overhead 2.4   --eaf 1   --depth 1000   --buckets 60
///   --large-line-count 40000   --large-byte-count 1000000
///   --min-gen-line-length 255   --file-gc-count 10000   --directory-walker-job-workers 8
///   --exclude-dir [.git,.hg,.svn]
///   --exclude-file [package-lock.json,Cargo.lock,yarn.lock,pubspec.lock,Podfile.lock,pnpm-lock.yaml]
///   --generated-markers [do not edit,<auto-generated />]
/// </summary>
public sealed class AnalysisOptions
{
    // ------------------------------------------------------------------
    // Exclusions & ignored files
    // ------------------------------------------------------------------

    /// <summary>Extra directories to skip, on top of the built-in .git/.hg/.svn.</summary>
    [JsonPropertyName("excludeDirectories")]
    public ObservableCollection<string> ExcludeDirectories { get; set; } = new();

    /// <summary>Extra file names to skip, on top of the built-in lock-file list.</summary>
    [JsonPropertyName("excludeFiles")]
    public ObservableCollection<string> ExcludeFiles { get; set; } = new();

    /// <summary>Additional gitignore-format ignore files applied from the scan root.</summary>
    [JsonPropertyName("ignoreFiles")]
    public ObservableCollection<string> IgnoreFiles { get; set; } = new();

    /// <summary>Regular expressions for files and directories to skip.</summary>
    [JsonPropertyName("notMatchRegexes")]
    public ObservableCollection<string> NotMatchRegexes { get; set; } = new();

    /// <summary>Honour .ignore files (<c>--no-ignore</c>).</summary>
    [JsonPropertyName("honourIgnoreFiles")]
    public bool HonourIgnoreFiles { get; set; } = true;

    /// <summary>Honour .sccignore files (<c>--no-scc-ignore</c>).</summary>
    [JsonPropertyName("honourSccIgnore")]
    public bool HonourSccIgnore { get; set; } = true;

    /// <summary>Honour .gitignore files (<c>--no-gitignore</c>).</summary>
    [JsonPropertyName("honourGitIgnore")]
    public bool HonourGitIgnore { get; set; } = true;

    /// <summary>Honour .gitmodules files (<c>--no-gitmodule</c>).</summary>
    [JsonPropertyName("honourGitModules")]
    public bool HonourGitModules { get; set; } = true;

    /// <summary>Count files that ignore rules would normally exclude (<c>--count-ignore</c>).</summary>
    [JsonPropertyName("countIgnoredFiles")]
    public bool CountIgnoredFiles { get; set; }

    // ------------------------------------------------------------------
    // File filtering
    // ------------------------------------------------------------------

    /// <summary>Only count files with these extensions (<c>--include-ext</c>).</summary>
    [JsonPropertyName("includeExtensions")]
    public ObservableCollection<string> IncludeExtensions { get; set; } = new();

    /// <summary>Never count files with these extensions (<c>--exclude-ext</c>).</summary>
    [JsonPropertyName("excludeExtensions")]
    public ObservableCollection<string> ExcludeExtensions { get; set; } = new();

    /// <summary>Drop files over the line/byte thresholds (<c>--no-large</c>).</summary>
    [JsonPropertyName("skipLargeFiles")]
    public bool SkipLargeFiles { get; set; }

    /// <summary><c>--large-line-count</c>.</summary>
    [JsonPropertyName("largeFileLineCount")]
    public long LargeFileLineCount { get; set; } = 40000;

    /// <summary><c>--large-byte-count</c>.</summary>
    [JsonPropertyName("largeFileByteCount")]
    public long LargeFileByteCount { get; set; } = 1000000;

    /// <summary>Flag minified files (<c>--min</c>).</summary>
    [JsonPropertyName("detectMinifiedFiles")]
    public bool DetectMinifiedFiles { get; set; }

    /// <summary>Flag generated files (<c>--gen</c>).</summary>
    [JsonPropertyName("detectGeneratedFiles")]
    public bool DetectGeneratedFiles { get; set; }

    /// <summary>Flag minified or generated files (<c>--min-gen</c>).</summary>
    [JsonPropertyName("detectMinifiedOrGenerated")]
    public bool DetectMinifiedOrGenerated { get; set; }

    /// <summary>Hide minified files from the results (<c>--no-min</c>, implies <c>--min</c>).</summary>
    [JsonPropertyName("excludeMinifiedFiles")]
    public bool ExcludeMinifiedFiles { get; set; }

    /// <summary>Hide generated files from the results (<c>--no-gen</c>, implies <c>--gen</c>).</summary>
    [JsonPropertyName("excludeGeneratedFiles")]
    public bool ExcludeGeneratedFiles { get; set; }

    /// <summary>Hide minified/generated files (<c>--no-min-gen</c>, implies <c>--min-gen</c>).</summary>
    [JsonPropertyName("excludeMinifiedOrGenerated")]
    public bool ExcludeMinifiedOrGenerated { get; set; }

    /// <summary>Average bytes per line above which a file counts as minified (<c>--min-gen-line-length</c>).</summary>
    [JsonPropertyName("minGeneratedLineByteLength")]
    public int MinGeneratedLineByteLength { get; set; } = 255;

    /// <summary>Extra head markers that mark a file as generated (<c>--generated-markers</c>).</summary>
    [JsonPropertyName("generatedMarkers")]
    public ObservableCollection<string> GeneratedMarkers { get; set; } = new();

    /// <summary>Detect binary files by NUL byte (<c>--binary</c> turns detection off).</summary>
    [JsonPropertyName("detectBinaryFiles")]
    public bool DetectBinaryFiles { get; set; } = true;

    /// <summary>Count symlink targets (<c>--include-symlinks</c>).</summary>
    [JsonPropertyName("includeSymlinks")]
    public bool IncludeSymlinks { get; set; }

    /// <summary>Count unrecognised extensions as an "Unknown" language (<c>--count-unsupported</c>).</summary>
    [JsonPropertyName("countUnsupportedAsText")]
    public bool CountUnsupportedAsText { get; set; }

    /// <summary>Remove duplicate files from the stats (<c>--no-duplicates</c>).</summary>
    [JsonPropertyName("removeDuplicates")]
    public bool RemoveDuplicates { get; set; }

    // ------------------------------------------------------------------
    // Language classification
    // ------------------------------------------------------------------

    /// <summary>Map an extension to a language: <c>jsp:html</c> (<c>--count-as</c>).</summary>
    [JsonPropertyName("countAs")]
    public string CountAs { get; set; } = string.Empty;

    /// <summary>Path-pattern categories backed by a base language (<c>--count-as-pattern</c>).</summary>
    [JsonPropertyName("countAsPatterns")]
    public ObservableCollection<string> CountAsPatterns { get; set; } = new();

    /// <summary>Remap unknown files by content sniffing (<c>--remap-unknown</c>).</summary>
    [JsonPropertyName("remapUnknown")]
    public string RemapUnknown { get; set; } = string.Empty;

    /// <summary>Remap every file by content sniffing (<c>--remap-all</c>).</summary>
    [JsonPropertyName("remapAll")]
    public string RemapAll { get; set; } = string.Empty;

    // ------------------------------------------------------------------
    // Output & formatting
    // ------------------------------------------------------------------

    /// <summary>Produce per-file rows as well as the per-language rollup (<c>--by-file</c>).</summary>
    [JsonPropertyName("perFileOutput")]
    public bool PerFileOutput { get; set; } = true;

    /// <summary>Add percentage columns (<c>--percent</c>).</summary>
    [JsonPropertyName("showPercentages")]
    public bool ShowPercentages { get; set; }

    /// <summary>Wide tabular output (<c>--wide</c>).</summary>
    [JsonPropertyName("wideOutput")]
    public bool WideOutput { get; set; }

    /// <summary>Force ASCII/CI-safe output (<c>--ci</c>).</summary>
    [JsonPropertyName("ciOutput")]
    public bool CiOutput { get; set; }

    /// <summary><c>--verbose</c>.</summary>
    [JsonPropertyName("verbose")]
    public bool Verbose { get; set; }

    /// <summary><c>--debug</c>.</summary>
    [JsonPropertyName("debug")]
    public bool Debug { get; set; }

    /// <summary><c>--trace</c>.</summary>
    [JsonPropertyName("trace")]
    public bool Trace { get; set; }

    /// <summary>Use per-language specialised counters where available (<c>--exp-per-language-counters</c>).</summary>
    [JsonPropertyName("usePerLanguageCounters")]
    public bool UsePerLanguageCounters { get; set; }

    /// <summary>Project identifier used for the SQL output formats (<c>--sql-project</c>).</summary>
    [JsonPropertyName("sqlProject")]
    public string SqlProject { get; set; } = string.Empty;

    // ------------------------------------------------------------------
    // Metrics & cost estimates
    // ------------------------------------------------------------------

    /// <summary>Compute unique lines of code (<c>--uloc</c>).</summary>
    [JsonPropertyName("computeUloc")]
    public bool ComputeUloc { get; set; } = true;

    /// <summary>Compute DRYness, which implies ULOC (<c>--dryness</c>).</summary>
    [JsonPropertyName("computeDryness")]
    public bool ComputeDryness { get; set; }

    /// <summary>Compute nesting-weighted (cognitive) complexity (<c>--cognitive</c>).</summary>
    [JsonPropertyName("computeCognitive")]
    public bool ComputeCognitive { get; set; }

    /// <summary>Skip code-complexity counting (<c>--no-complexity</c>).</summary>
    [JsonPropertyName("skipComplexity")]
    public bool SkipComplexity { get; set; }

    /// <summary>Skip the COCOMO estimate (<c>--no-cocomo</c>).</summary>
    [JsonPropertyName("skipCocomo")]
    public bool SkipCocomo { get; set; }

    /// <summary>COCOMO model type: organic, semi-detached, embedded or custom,a,b,c,d.</summary>
    [JsonPropertyName("cocomoProjectType")]
    public string CocomoProjectType { get; set; } = "organic";

    /// <summary>Average yearly wage used by COCOMO (<c>--avg-wage</c>).</summary>
    [JsonPropertyName("averageWage")]
    public long AverageWage { get; set; } = 56286;

    /// <summary>Corporate overhead multiplier (<c>--overhead</c>).</summary>
    [JsonPropertyName("overhead")]
    public double Overhead { get; set; } = 2.4;

    /// <summary>Effort adjustment factor, 1.0 when nominal (<c>--eaf</c>).</summary>
    [JsonPropertyName("effortAdjustmentFactor")]
    public double EffortAdjustmentFactor { get; set; } = 1.0;

    /// <summary>Render COCOMO in SLOCCount style (<c>--sloccount-format</c>).</summary>
    [JsonPropertyName("sloccountFormat")]
    public bool SloccountFormat { get; set; }

    /// <summary>Size unit for the tabular byte column (<c>--size-unit</c>).</summary>
    [JsonPropertyName("sizeUnit")]
    public string SizeUnit { get; set; } = "si";

    /// <summary>Skip the size column (<c>--no-size</c>).</summary>
    [JsonPropertyName("skipSize")]
    public bool SkipSize { get; set; }

    /// <summary>Currency symbol used by the cost estimates (<c>--currency-symbol</c>).</summary>
    [JsonPropertyName("currencySymbol")]
    public string CurrencySymbol { get; set; } = "$";

    /// <summary>Enable the LOCOMO estimate (<c>--locomo</c>).</summary>
    [JsonPropertyName("estimateLocomo")]
    public bool EstimateLocomo { get; set; } = true;

    /// <summary>Show COCOMO and LOCOMO side by side (<c>--cost-comparison</c>).</summary>
    [JsonPropertyName("compareCosts")]
    public bool CompareCosts { get; set; }

    /// <summary>LOCOMO model preset: large, medium, small or local (<c>--locomo-preset</c>).</summary>
    [JsonPropertyName("locomoPreset")]
    public string LocomoPreset { get; set; } = "medium";

    /// <summary>Human review minutes per line of code (<c>--locomo-review</c>).</summary>
    [JsonPropertyName("locomoReviewMinutesPerLine")]
    public double LocomoReviewMinutesPerLine { get; set; } = 0.01;

    /// <summary>LOCOMO cost per 1M input tokens, overrides the preset (<c>--locomo-input-price</c>).</summary>
    [JsonPropertyName("locomoInputPrice")]
    public double LocomoInputPrice { get; set; }

    /// <summary>LOCOMO cost per 1M output tokens, overrides the preset (<c>--locomo-output-price</c>).</summary>
    [JsonPropertyName("locomoOutputPrice")]
    public double LocomoOutputPrice { get; set; }

    /// <summary>LOCOMO output tokens per second, overrides the preset (<c>--locomo-tps</c>).</summary>
    [JsonPropertyName("locomoTokensPerSecond")]
    public double LocomoTokensPerSecond { get; set; }

    /// <summary>Override the estimated LLM iteration cycles (<c>--locomo-cycles</c>).</summary>
    [JsonPropertyName("locomoCycles")]
    public double LocomoCycles { get; set; }

    /// <summary>
    /// Power-user LOCOMO config
    /// <c>tokensPerLine,inputPerLine,complexityWeight,iterations,iterationWeight</c>.
    /// </summary>
    [JsonPropertyName("locomoConfig")]
    public string LocomoConfig { get; set; } = string.Empty;

    // ------------------------------------------------------------------
    // Git history
    // ------------------------------------------------------------------

    /// <summary>Commit window for the history sections; 0 means all history (<c>--depth</c>).</summary>
    [JsonPropertyName("historyDepth")]
    public long HistoryDepth { get; set; } = 1000;

    /// <summary>Time-bucket resolution for the timelines (<c>--buckets</c>).</summary>
    [JsonPropertyName("timelineBuckets")]
    public int TimelineBuckets { get; set; } = 60;

    /// <summary>Fold author identities by name + email domain (<c>--no-fold-authors</c> disables).</summary>
    [JsonPropertyName("foldAuthors")]
    public bool FoldAuthors { get; set; } = true;

    // The engine's report path always ranks change coupling by raw co-change
    // counts: its <c>--sort</c>, <c>--coupling-weighted</c> and
    // <c>--coupling-for</c> switches only shape the CLI's own tables, so the
    // application neither shows nor forwards them.

    // ------------------------------------------------------------------
    // Performance / worker tuning
    // ------------------------------------------------------------------

    /// <summary>Files to parse before re-enabling the GC (<c>--file-gc-count</c>).</summary>
    [JsonPropertyName("fileGcCount")]
    public int FileGcCount { get; set; } = 10000;

    /// <summary>Queue of files waiting to be read (<c>--file-list-queue-size</c>, 0 = auto).</summary>
    [JsonPropertyName("fileListQueueSize")]
    public int FileListQueueSize { get; set; }

    /// <summary>Goroutines that count a file (<c>--file-process-job-workers</c>, 0 = auto).</summary>
    [JsonPropertyName("fileProcessJobWorkers")]
    public int FileProcessJobWorkers { get; set; }

    /// <summary>Goroutines that turn paths into jobs (<c>--file-list-job-workers</c>, 0 = auto).</summary>
    [JsonPropertyName("fileListJobWorkers")]
    public int FileListJobWorkers { get; set; }

    /// <summary>Queue holding finished file stats (<c>--file-summary-job-queue-size</c>, 0 = auto).</summary>
    [JsonPropertyName("fileSummaryJobQueueSize")]
    public int FileSummaryJobQueueSize { get; set; }

    /// <summary>Directory-walking workers (<c>--directory-walker-job-workers</c>).</summary>
    [JsonPropertyName("directoryWalkerJobWorkers")]
    public int DirectoryWalkerJobWorkers { get; set; } = 8;

    /// <summary>A deep copy, used by presets so edits never alias the original.</summary>
    public AnalysisOptions Clone()
    {
        // System.Text.Json round-trip: the option surface is flat records and
        // lists of strings/numbers, so this is both simple and exact.
        var json = System.Text.Json.JsonSerializer.Serialize(this);
        return System.Text.Json.JsonSerializer.Deserialize<AnalysisOptions>(json)!;
    }
}
